<script lang="ts">
    import { onMount } from 'svelte';

    type Prospect = {
        id: number;
        name: string;
        email: string;
        phone: string | null;
        status: string;
    };

    let prospects: Prospect[] = [];
    let loading = true;

    async function loadData() {
        try {
            const res = await fetch('/api/v1/prospects?workspaceId=1');
            if (res.ok) {
                prospects = await res.json();
            }
        } catch (err) {
            console.error('Failed to load prospects', err);
        } finally {
            loading = false;
        }
    }

    onMount(() => {
        loadData();
        const interval = setInterval(loadData, 3000); // Polling for POC
        return () => clearInterval(interval);
    });

    async function approve(id: number) {
        try {
            const res = await fetch(`/api/v1/prospects/${id}`, {
                method: 'PATCH',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ status: 'approved' })
            });

            if (res.ok) {
                const updated = await res.json();
                prospects = prospects.map(p => p.id === id ? updated : p);
            }
        } catch (err) {
            console.error('Failed to approve', err);
        }
    }
</script>

<svelte:head>
    <title>QuestPage Dashboard</title>
</svelte:head>

<div class="container mt-lg">
    <div class="page-head">
        <div>
            <h1 class="page-title">QuestPage Dashboard</h1>
            <p class="page-sub">Manage and approve incoming leads generated by your AI secretary.</p>
        </div>
        <button on:click={loadData} class="btn btn-secondary btn-sm">
            Refresh Data
        </button>
    </div>

    {#if loading && prospects.length === 0}
        <div class="muted">Loading prospects...</div>
    {:else}
        <table class="t">
            <thead>
                <tr>
                    <th>ID</th>
                    <th>Name</th>
                    <th>Email</th>
                    <th>Phone</th>
                    <th>Status</th>
                    <th>Action</th>
                </tr>
            </thead>
            <tbody>
                {#each prospects as item (item.id)}
                    <tr class={item.status === 'approved' ? 'approved-row' : ''}>
                        <td class="muted">{item.id}</td>
                        <td style="font-weight: 500;">{item.name}</td>
                        <td>{item.email}</td>
                        <td>{item.phone || '-'}</td>
                        <td>
                            <span class="badge {item.status === 'approved' ? 'badge-emerald' : 'badge-warning'}">
                                {item.status}
                            </span>
                        </td>
                        <td>
                            {#if item.status !== 'approved'}
                                <button 
                                    on:click={() => approve(item.id)}
                                    class="btn btn-sm"
                                >
                                    Approve
                                </button>
                            {:else}
                                <span class="muted-soft">Approved</span>
                            {/if}
                        </td>
                    </tr>
                {/each}
                {#if prospects.length === 0}
                    <tr>
                        <td colspan="6" class="center" style="padding: var(--s-xl); color: var(--c-muted);">No prospects found.</td>
                    </tr>
                {/if}
            </tbody>
        </table>
    {/if}
</div>

